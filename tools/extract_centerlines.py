#!/usr/bin/env python3
"""Turn the Excalidraw freedraw SVGs in numbers/ into snake-friendly centerlines.

Excalidraw exports freedraw strokes as filled perfect-freehand outlines, not as
lines. Such an outline walks down one side of the stroke, around the end cap and
back up the other side, so the centerline can be recovered by finding the tip
around which the outline is mirror-symmetric and averaging each pair of mirrored
points. The outline begins next to the stroke's start, which gives the writing
direction.

Output: numbers/glyphs.js (sets window.GLYPHS, so index.html also works via file://)
  { "<digit>": [ variant, ... ] }
  variant = { "w": width, "h": height, "strokes": [ [x,y, x,y, ...], ... ] }
Stroke width is left out on purpose: the mirrored-pair widths are noisy, and the
snake is drawn with its own constant width anyway.
All coordinates are normalised so the ink of every glyph is 100 units tall.
"""
import glob, json, os, re
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEIGHT = 100.0   # normalised ink height
STEP = 2.0       # resample spacing in normalised units


def outlines(fn):
    s = open(fn).read()
    pat = r'<g transform="translate\(([-\d.e]+) ([-\d.e]+)\)[^"]*"[^>]*><path[^>]* d="([^"]+)"'
    for m in re.finditer(pat, s):
        tx, ty, d = float(m.group(1)), float(m.group(2)), m.group(3)
        coords = d.split('Q', 1)[1].split('L')[0].split()
        pts = np.array([tuple(map(float, c.split(','))) for c in coords[0::2]]) + [tx, ty]
        keep = [0] + [i for i in range(1, len(pts)) if np.linalg.norm(pts[i] - pts[i - 1]) > 1e-6]
        yield pts[keep]


def centerline(P):
    n, half = len(P), len(P) // 2
    idx = np.arange(1, half)
    costs = [np.linalg.norm(P[(c + idx) % n] - P[(c - idx) % n], axis=1).mean() for c in range(n)]
    c = int(np.argmin(costs))
    a = P[(c + np.arange(half + 1)) % n]
    b = P[(c - np.arange(half + 1)) % n]
    mid, width = (a + b) / 2, np.linalg.norm(a - b, axis=1)
    if np.linalg.norm(mid[-1] - P[0]) < np.linalg.norm(mid[0] - P[0]):
        mid, width = mid[::-1], width[::-1]
    return mid, width


def smooth(a, k=2):
    if len(a) < 2 * k + 1:
        return a
    out = a.copy()
    for i in range(k, len(a) - k):
        out[i] = a[i - k:i + k + 1].mean(axis=0)
    return out


def resample(mid, width, step):
    seg = np.linalg.norm(np.diff(mid, axis=0), axis=1)
    s = np.concatenate([[0], np.cumsum(seg)])
    n = max(2, int(round(s[-1] / step)) + 1)
    t = np.linspace(0, s[-1], n)
    x = np.interp(t, s, mid[:, 0]); y = np.interp(t, s, mid[:, 1])
    w = np.interp(t, s, width)
    return np.stack([x, y], 1), w


def main():
    glyphs = {}
    for digit in range(10):
        variants = []
        for fn in sorted(glob.glob(os.path.join(ROOT, 'numbers', str(digit), '*.svg'))):
            strokes = []
            for P in outlines(fn):
                mid, w = centerline(P)
                mid = smooth(mid)
                w = smooth(w[:, None], 3)[:, 0]
                strokes.append((mid, w))
            allpts = np.concatenate([m for m, _ in strokes])
            lo, hi = allpts.min(0), allpts.max(0)
            scale = HEIGHT / (hi[1] - lo[1])
            out = []
            for mid, w in strokes:
                m = (mid - lo) * scale
                m, r = resample(m, w * scale / 2, STEP)
                out.append([round(float(v), 1) for v in m.flatten()])
            variants.append({'w': round(float((hi[0] - lo[0]) * scale), 1), 'h': HEIGHT, 'strokes': out})
        glyphs[str(digit)] = variants
    with open(os.path.join(ROOT, 'numbers', 'glyphs.js'), 'w') as f:
        f.write('// Generated by tools/extract_centerlines.py - do not edit by hand.\n')
        f.write('window.GLYPHS = ')
        json.dump(glyphs, f, separators=(',', ':'))
        f.write(';\n')


if __name__ == '__main__':
    main()
